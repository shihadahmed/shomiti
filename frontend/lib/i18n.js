const dictionaries = { en, bn };
const STORAGE_KEY = 'shomiti.lang';
const LOCALES = ['bn', 'en'];

export function getLang() {
  if (typeof window === 'undefined') return 'en';
  const stored = localStorage.getItem(STORAGE_KEY);
  return LOCALES.includes(stored) ? stored : 'en';
}

export function setLang(lang) {
  if (!LOCALES.includes(lang)) return;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

export function t(key, params) {
  const lang = getLang();
  const dict = dictionaries[lang] || dictionaries.en;
  const template = dict[key] || key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => {
    return params && params[name] !== undefined ? String(params[name]) : `{${name}}`;
  });
}

export function formatMoney(value, opts) {
  const locale = getLang() === 'bn' ? 'bn-BD' : 'en-BD';
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: 'BDT',
    notation: opts?.compact ? 'compact' : 'standard',
    maximumFractionDigits: opts?.compact ? 1 : 2,
    minimumFractionDigits: opts?.compact ? 0 : 0,
  }).format(value / 100);
}

export function formatNumber(value, opts) {
  const locale = getLang() === 'bn' ? 'bn-BD' : 'en-BD';
  return new Intl.NumberFormat(locale, {
    notation: opts?.compact ? 'compact' : 'standard',
    maximumFractionDigits: opts?.maximumFractionDigits ?? 0,
  }).format(value);
}

export function formatDate(value, opts) {
  if (!value) return t('common.na');
  const date = new Date(value);
  if (isNaN(date.getTime())) return t('common.na');
  const locale = getLang() === 'bn' ? 'bn-BD' : 'en-GB';
  return new Intl.DateTimeFormat(locale, {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    ...(opts?.time ? { hour: '2-digit', minute: '2-digit' } : {}),
  }).format(date);
}

export function formatDateTime(value) {
  return formatDate(value, { time: true });
}

export function initials(name) {
  return name
    .trim()
    .split(/\s+/)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() || '')
    .join('') || '?';
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  root.querySelectorAll('[data-lang]').forEach((el) => {
    el.setAttribute('aria-pressed', String(el.getAttribute('data-lang') === getLang()));
  });
}

export function initI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  applyTranslations();
}

export { LOCALES, dictionaries };
